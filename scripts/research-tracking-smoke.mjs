import assert from 'node:assert/strict';
import { resolve } from 'node:path';

export async function verifyResearchTracking(page, origin, root) {
  await page.getByRole('button',{name:/A股验证公司/}).first().click();
  const business=page.getByRole('region',{name:'分业务经营数据',exact:true});
  const hypotheses=page.getByRole('region',{name:'研究假设跟踪',exact:true});
  await business.getByRole('button',{name:'录入业务数据'}).click();
  assert.equal(await business.getByLabel('披露数值',{exact:true}).inputValue(),'');
  await business.getByLabel('业务／产品／地区名称',{exact:true}).fill('广告');
  await business.getByLabel('报告期起始',{exact:true}).fill('2025-01-01');
  await business.getByLabel('报告期结束',{exact:true}).fill('2025-12-31');
  await business.getByLabel('披露数值',{exact:true}).fill('120');
  await business.getByLabel('报告名称／来源',{exact:true}).fill('2025年报');
  await business.getByLabel('原报告链接（选填）',{exact:true}).fill('https://example.com/report');
  await business.getByLabel('页码／附注位置',{exact:true}).fill('第50页');
  await business.getByRole('button',{name:'保存业务数据'}).click();
  await business.getByRole('button',{name:'建立假设'}).waitFor();
  const endpoint=`${origin}/api/finance/research/a/600519`;
  let state=await (await fetch(endpoint)).json();
  assert.equal(state.business.length,1);
  const actual=state.business[0];
  async function post(path,data,method='POST') {
    const response=await fetch(`${endpoint}${path}`,{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
    assert.equal(response.ok,true,await response.clone().text()); return response.json();
  }
  await post('/business',{...actual.data,expectedVersion:0,periodStart:'2024-01-01',periodEnd:'2024-12-31',value:100});
  await post('/business',{...actual.data,expectedVersion:0,dimension:'整体',segment:'公司整体',value:300});
  await post('/business',{...actual.data,expectedVersion:0,metric:'毛利',value:48});
  await page.getByRole('button',{name:'重新载入研究记录与估值快照'}).click();
  const row=business.locator('tbody tr').filter({has:page.getByText('业务 · 收入',{exact:true})}).filter({hasText:'广告'});
  await row.getByRole('button',{name:'建立假设'}).waitFor();
  assert.ok((await row.innerText()).includes('20.00%'));
  assert.ok((await row.innerText()).includes('40.00%'));
  await row.getByRole('button',{name:'建立假设'}).click();
  await hypotheses.getByLabel('研究假设',{exact:true}).fill('广告收入至少125亿元');
  await hypotheses.getByLabel('预期下限（含）',{exact:true}).fill('125');
  await hypotheses.getByLabel('预期上限（含）',{exact:true}).fill('140');
  await hypotheses.getByLabel('计划验证日期',{exact:true}).fill('2026-04-30');
  await hypotheses.getByLabel('假设依据／证据来源',{exact:true}).fill('依据订单增长和年报第50页');
  const valuation=await (await fetch(`${origin}/api/finance/valuation-models/a/600519`)).json();
  await hypotheses.getByLabel(/^关联估值快照/).selectOption(String(valuation[0].id));
  await hypotheses.getByRole('button',{name:'保存研究假设'}).click();
  await hypotheses.getByText('指标偏离·待验证',{exact:true}).waitFor();
  await hypotheses.getByRole('button',{name:'验证假设',exact:true}).click();
  await hypotheses.getByLabel('验证结论与原因',{exact:true}).fill('收入低于预期，需检查广告需求');
  await hypotheses.getByLabel('对估值／投资逻辑的影响',{exact:true}).fill('下调中性增长假设，另存估值');
  await hypotheses.getByRole('button',{name:'记录本次验证'}).click();
  await hypotheses.getByText('已验证·指标偏离',{exact:true}).waitFor();
  state=await (await fetch(endpoint)).json();
  assert.equal(state.hypotheses[0].data.review.actual,120);
  assert.equal(state.hypotheses[0].data.valuationSnapshotId,valuation[0].id);
  const initialVersion=state.hypotheses[0].version;
  await row.getByRole('button',{name:'编辑',exact:true}).click();
  await business.getByLabel('披露数值',{exact:true}).fill('130');
  await business.getByRole('button',{name:'保存业务数据'}).click();
  await hypotheses.getByText('数据已修订·需重验',{exact:true}).waitFor();
  await hypotheses.getByRole('button',{name:'验证假设',exact:true}).click();
  await hypotheses.getByLabel('验证结论与原因',{exact:true}).fill('修订报告后收入达标');
  await hypotheses.getByLabel('对估值／投资逻辑的影响',{exact:true}).fill('恢复增长假设，保留原验证记录');
  await hypotheses.getByRole('button',{name:'记录本次验证'}).click();
  await hypotheses.getByText('已验证·指标达标',{exact:true}).waitFor();
  await hypotheses.getByRole('button',{name:'查看历史',exact:true}).click();
  const history=page.getByRole('region',{name:'研究记录历史'});
  await history.getByText(/实际 120/).waitFor();
  assert.ok((await history.innerText()).includes('实际 130'));
  state=await (await fetch(endpoint)).json();
  const h=state.hypotheses[0];
  const conflict=await fetch(`${endpoint}/hypotheses/${h.id}`,{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({...h.data,expectedVersion:initialVersion})});
  assert.equal(conflict.status,409);
  const foreign=await fetch(`${origin}/api/finance/research/hk/00700/hypotheses/${h.id}/history`);
  assert.equal(foreign.status,404);
  await business.screenshot({path:resolve(root,'data/business-tracking.png'),style:'.topbar { visibility:hidden !important; }'});
  await hypotheses.screenshot({path:resolve(root,'data/hypothesis-tracking.png'),style:'.topbar { visibility:hidden !important; }'});
  await page.reload();
  await hypotheses.getByText('已验证·指标达标',{exact:true}).waitFor();
  await hypotheses.getByRole('button',{name:'归档假设',exact:true}).click();
  await hypotheses.getByLabel(/^筛选假设/).selectOption('all');
  await hypotheses.getByText('已归档',{exact:true}).waitFor();
  await hypotheses.getByRole('button',{name:'恢复跟踪',exact:true}).click();
  await hypotheses.getByText('指标达标·待验证',{exact:true}).waitFor();
  await page.getByRole('button',{name:/港股验证公司/}).first().click();
  await business.getByText(/当前期间没有可用业务数据/).waitFor();
  assert.equal(await hypotheses.getByText('广告收入至少125亿元',{exact:true}).count(),0);
  console.log('PASS: business entry/comparison, linked hypothesis, verification, source revision, immutable history, conflict checks, reload, archive/reopen, company isolation.');
}
